#!/usr/bin/env python3
"""Write STRUCTURE.md: every path in the project tree, fully expanded.

Generated rather than authored, like DATASETS.md and PROVENANCE.md, so it can
be regenerated instead of drifting.

Two subtrees are COLLAPSED to a single counted line each, and nothing else is:

``.git``
    Version-control internals. Thousands of object files whose names are
    content hashes; they describe git's storage, not this project.
``scripts/.venv``
    The Python virtualenv - third-party packages installed from PyPI. Not
    project structure, and the largest single contributor at ~22k paths.

Everything else is listed in full, including every generated artefact, every
checkpoint and every superseded directory, because which generated files exist
is part of what the tree says about the run.
"""
from __future__ import annotations

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COLLAPSE = {".git", "scripts/.venv"}
OUT = ROOT / "STRUCTURE.md"


def human(n: int) -> str:
    for unit in ("B", "kB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024.0
    return f"{n:.1f} TB"


def main() -> int:
    rows: list[str] = []
    collapsed: dict[str, tuple[int, int]] = {}
    n_dirs = n_files = n_links = 0
    total_bytes = 0

    for dirpath, dirnames, filenames in os.walk(ROOT, followlinks=False):
        rel_dir = Path(dirpath).relative_to(ROOT)
        rel_s = "." if str(rel_dir) == "." else str(rel_dir)

        # Collapse: count the subtree, record it, and do not descend.
        if rel_s in COLLAPSE:
            c = b = 0
            for dp, dn, fn in os.walk(dirpath, followlinks=False):
                c += len(dn) + len(fn)
                for f in fn:
                    try:
                        b += os.lstat(os.path.join(dp, f)).st_size
                    except OSError:
                        pass
            collapsed[rel_s] = (c, b)
            dirnames[:] = []
            continue
        dirnames[:] = sorted(d for d in dirnames if f"{rel_s}/{d}".lstrip("./") not in COLLAPSE
                             or True)
        dirnames.sort()

        if rel_s != ".":
            n_dirs += 1
            rows.append(f"{rel_s}/")
        for name in sorted(filenames):
            p = Path(dirpath) / name
            rel = f"{rel_s}/{name}" if rel_s != "." else name
            try:
                st = os.lstat(p)
            except OSError:
                rows.append(f"{rel}    (unreadable)")
                continue
            if os.path.islink(p):
                n_links += 1
                rows.append(f"{rel} -> {os.readlink(p)}")
            else:
                n_files += 1
                total_bytes += st.st_size
                rows.append(rel)

    # Collapsed subtrees are listed where they belong, in sorted order.
    for name, (count, nbytes) in collapsed.items():
        rows.append(f"{name}/    [COLLAPSED: {count:,} paths, {human(nbytes)} "
                    f"- see the note at the top]")
    rows.sort()

    top = sorted(p.name + ("/" if p.is_dir() else "") for p in ROOT.iterdir())
    real = ROOT.resolve()
    n_old_path = sum(1 for r in rows if "Desktop/HRSD_Occupants" in r)

    with OUT.open("w", encoding="utf-8") as fh:
        fh.write("# Project structure\n\n")
        fh.write("Generated by `scripts/gen_structure.py`; do not hand-edit.\n\n")
        REQUESTED = Path("/Users/brianoregan/Desktop/HRSD_Occupants")
        fh.write(f"**Real root:** `{real}`\n\n")
        if REQUESTED.is_symlink():
            fh.write(f"**Also reachable as:** `{REQUESTED}` — a symlink to "
                     f"`{os.readlink(REQUESTED)}`.\n\n")
            fh.write("The tree was moved out of `~/Desktop` because macOS TCC "
                     "denies launchd access to it, which made the LaunchAgent exit "
                     "126 (I-107); granting Full Disk Access was explicitly not "
                     "wanted. A symlink was left at the old path so every absolute "
                     "path already written into the repo keeps resolving — and "
                     f"{n_old_path} symlinks inside this tree still point at the "
                     "old path, so **removing that symlink would break them**. They "
                     "are listed below with their targets.\n\n")
        fh.write(f"| | |\n|---|---|\n")
        fh.write(f"| directories listed | {n_dirs:,} |\n")
        fh.write(f"| files listed | {n_files:,} |\n")
        fh.write(f"| symlinks listed | {n_links:,} |\n")
        fh.write(f"| bytes in listed files | {human(total_bytes)} |\n")
        for name, (count, nbytes) in sorted(collapsed.items()):
            fh.write(f"| `{name}` (collapsed) | {count:,} paths, {human(nbytes)} |\n")
        fh.write("\n## What is collapsed, and why\n\n")
        fh.write("Everything in this tree is listed in full except two subtrees:\n\n")
        fh.write("- **`.git`** — version-control internals: object files named by "
                 "content hash. They describe git's storage, not this project.\n")
        fh.write("- **`scripts/.venv`** — the Python virtualenv, i.e. third-party "
                 "packages from PyPI. Not project structure, and the single largest "
                 "contributor to the path count.\n\n")
        fh.write("Nothing else is omitted. Every generated artefact, every "
                 "checkpoint and every superseded directory is listed, because "
                 "which generated files exist is itself part of what the tree "
                 "records about the run.\n\n")
        fh.write("## Top level\n\n")
        for t in top:
            fh.write(f"- `{t}`\n")
        fh.write(f"\n## Every path\n\n```\n")
        for r in rows:
            fh.write(r + "\n")
        fh.write("```\n")

    print(f"wrote {OUT}")
    print(f"  {n_dirs:,} dirs, {n_files:,} files, {n_links:,} symlinks, "
          f"{human(total_bytes)}")
    for name, (c, b) in sorted(collapsed.items()):
        print(f"  collapsed {name}: {c:,} paths, {human(b)}")
    print(f"  {OUT.stat().st_size/2**20:.2f} MB, "
          f"{sum(1 for _ in OUT.open(encoding='utf-8')):,} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
