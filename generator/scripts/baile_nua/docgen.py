"""Generate the data dictionary for the evidence view from ``datasets.yaml``.

Design 8.5: "The YAML schema generates DDL, validators and docs."  This is the
docs half; :mod:`baile_nua.schema.validate` is the validators half.
"""

from __future__ import annotations

from pathlib import Path

from baile_nua.schema import AccessClass, load


def data_dictionary_markdown() -> str:
    s = load()
    out: list[str] = [
        "# Baile Nua — data dictionary",
        "",
        f"**{s.label}**",
        "",
        f"Generated from `baile_nua/schema/datasets.yaml` v{s.schema_version} "
        f"(design revision {s.design_revision}, frozen {s.design_frozen}). "
        "Do not edit this file; edit the schema.",
        "",
        "## Access classes",
        "",
        "| Class | Meaning | Release package |",
        "| --- | --- | --- |",
        "| GT | Ground truth. Never given to a model under test. | `v1/ground_truth/` |",
        "| OBS | Observable. What a device, respondent, assessor or operator would see. | `v1/observable/` |",
        "| META | Provenance and calibration. | `v1/evidence/` |",
        "",
        "## Units",
        "",
    ]
    for k, v in s.units.items():
        out.append(f"- **{k}**: {v}")
    out += ["", "## Inventory", "", "| ID | Dataset | Class | Grain | Subsystem | Fields |", "| --- | --- | --- | --- | --- | --- |"]
    for ds in s.datasets.values():
        out.append(
            f"| {ds.id} | `{ds.name}` | {ds.access_class} | {ds.grain} | "
            f"{ds.subsystem or '—'} | {len(ds.fields)} |"
        )

    for ds in s.datasets.values():
        out += ["", f"## {ds.id} `{ds.name}` — {ds.title}", ""]
        out.append(f"- **Access class:** {ds.access_class}")
        out.append(f"- **Grain:** {ds.grain}")
        out.append(f"- **Storage:** {ds.storage}")
        if ds.keyed_by:
            out.append(f"- **Keyed by:** {ds.keyed_by}")
        if ds.access_note:
            out.append(f"- **Access note:** {ds.access_note}")
        if ds.calibration_status:
            out.append(f"- **Calibration status:** {ds.calibration_status}")
        if ds.notes:
            out.append(f"- **Notes:** {ds.notes.strip()}")
        if ds.forbidden_field_patterns:
            out.append(
                "- **Forbidden field patterns:** "
                + ", ".join(f"`{p}`" for p in ds.forbidden_field_patterns)
            )
        out += [""]
        is_obs = ds.access_class == AccessClass.OBS
        header = "| Field | Type | Req | Unit / values | "
        header += "Mechanism (design 6.5 rule 1) | GT counterpart | " if is_obs else "Layer | "
        header += "Notes |"
        out.append(header)
        out.append("| --- | --- | --- | --- | " + ("--- | --- | " if is_obs else "--- | ") + "--- |")
        for f in ds.fields:
            vals = f.unit or ""
            if f.enum:
                vals = f"enum `{f.enum}`: " + ", ".join(map(str, s.enums[f.enum]))
            elif f.enum_values:
                vals = ", ".join(map(str, f.enum_values))
            mid = (
                f"{f.mechanism or ''} | {f.gt_counterpart or '—'} | "
                if is_obs
                else f"{f.layer or '—'} | "
            )
            notes = f.notes or ""
            if f.mimic_field:
                notes = f"MIMIC `{f.mimic_field}`. {notes}".strip()
            if f.forbidden:
                notes = f"**Must always be null.** {notes}".strip()
            out.append(
                f"| `{f.name}` | {f.type} | {'y' if f.required else ''} | {vals} | {mid}{notes} |"
            )
    return "\n".join(out) + "\n"


def write(path: str | Path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(data_dictionary_markdown(), encoding="utf-8")
    return p
